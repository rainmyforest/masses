def _strength_block(st):
    """日主强弱粗判（Q9）→ head 注入文本。"""
    tick = {True: "✓", False: "✗"}
    return f"""
**日主强弱粗判**（得令/得地/得势三要素，喜忌与大运十神解读的坐标参考）：
日主{st['日主']}，生于{st['月令']}：得令{tick[st['得令']]}、得地{tick[st['得地']]}、
得势{tick[st['得势']]}（同党权重 {st['同党权重']}）→ 粗判**{st['粗判']}**；
喜用倾向：{st['喜用倾向']}。
"""


def _dayun_block(dy):
    """大运流年事实（方案 3.1 窗口式）→ head 注入文本。

    窗口：当前大运 + 未来 2 步 + 当前年 ±3 流年（token 成本控制，
    全量大运流年表格由页面/附录承载，不进 prompt）。
    """
    q = dy["起运"]
    lines = [f"""
**大运流年事实**（推算层输出，请以此为解读依据；年龄为虚岁，流年干支
以立春分界——与八字年柱同口径）：
- 起运：{q['出生后']}交运（{q['交运时刻']}），起运虚岁 {q['起运虚岁']}，
  {q['排法']}（{q['流派']}）"""]
    cur = dy.get("当前大运")
    if cur:
        lines.append(f"- 当前大运：{cur['干支']}（{cur['十神']}/{cur['纳音']}），"
                     f"{cur['起岁']}-{cur['止岁']} 虚岁"
                     f"（{cur['起年']}-{cur['止年']}），第 {cur['序']} 步")
    elif dy.get("大运"):
        nxt = dy["大运"][0]
        lines.append(f"- 当前大运：尚未交运，{nxt['起年']} 年起进入第一步大运 "
                     f"{nxt['干支']}（{nxt['十神']}）")
    fut = "；".join(f"{s['干支']}（{s['十神']}/{s['纳音']}），"
                    f"{s['起岁']}-{s['止岁']} 虚岁（{s['起年']}-{s['止年']}）"
                    for s in dy.get("未来大运", []))
    if fut:
        lines.append(f"- 未来大运：{fut}")
    recent = "；".join(
        f"{r['年']} {r['干支']}（{r['十神']}，当前年）" if r.get("当前")
        else f"{r['年']} {r['干支']}（{r['十神']}）"
        for r in dy.get("近期流年", []))
    if recent:
        lines.append(f"- 近期流年（当前年前后 3 年）：{recent}")
    return "\n".join(lines) + "\n"


