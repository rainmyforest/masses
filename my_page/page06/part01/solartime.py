# 排盘时口径（页面选项，顺序即默认推荐：平太阳时为主流）
BEIJING = "北京时间（东经120°标准时，不校正）"
MEAN = "地方平太阳时（按出生地经度校正）"
TRUE = "真太阳时（平太阳时＋均时差）"
MODES = (MEAN, TRUE, BEIJING)


def equation_of_time(dt):
    """均时差（单位：分钟，正=真太阳快于平太阳）。

    NOAA 简化式：EoT = 9.87·sin2B − 7.53·cosB − 1.5·sinB，
    B = 360°/365 · (年积日 − 81)。锚点（天文年历通行值，测试可对拍）：
    2月中 ≈ −14.2，4月中/6月中 ≈ 0，7月末 ≈ −6.5，11月初 ≈ +16.4。
    """
    b = math.radians(360.0 / 365.0 * (dt.timetuple().tm_yday - 81))
    return 9.87 * math.sin(2 * b) - 7.53 * math.cos(b) - 1.5 * math.sin(b)


def adjust(dt, longitude, mode):
    """北京时间 datetime → 所选口径的 datetime。

    返回 (校正后 datetime, 经度校正分钟, 均时差分钟)。
    跨日/跨年由 timedelta 运算自动进退位。
    """
    lon_min = (float(longitude) - 120.0) * 4.0
    if mode == BEIJING:
        return dt, 0.0, 0.0
    if mode == MEAN:
        return dt + timedelta(minutes=lon_min), lon_min, 0.0
    eot = equation_of_time(dt)
    return dt + timedelta(minutes=lon_min + eot), lon_min, eot


